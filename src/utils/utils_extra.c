#include "minishell.h"

int	ft_isspace(int c)
{
	if (c == ' '
		|| c == '\t'
		|| c == '\n'
		|| c == '\v'
		|| c == '\f'
		|| c == '\f'
		|| c == '\r')
	{
		return (1);
	}
	return (0);
}

int	is_operator_char(char c)
{
	return (c == '|' || c == '<' || c == '>');
}
